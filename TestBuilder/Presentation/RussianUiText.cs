    public static string Display(object? value)
    {
        if (value is Parity parity) return parity switch
        {
            Parity.None => "Без чётности", Parity.Odd => "Нечётная", Parity.Even => "Чётная",
            Parity.Mark => "Постоянная 1", Parity.Space => "Постоянный 0", _ => parity.ToString()
        };
        if (value is StopBits stop) return stop switch
        {
            StopBits.One => "1", StopBits.Two => "2", StopBits.OnePointFive => "1,5", _ => "Не задано"
        };
        var key = value?.ToString() ?? string.Empty;
        return Labels.TryGetValue(key, out var label) ? label : key;
    }

